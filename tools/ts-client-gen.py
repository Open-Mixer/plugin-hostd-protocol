# The TypeScript client's vocabulary (doc/ts-client.md): every verb of protocol/plugin-hostd-protocol.json with its forms,
# refusal codes and reply, the argument types, the reply codes and the parse refusals, written as clients/typescript/vocabulary.mjs
# and its types, clients/typescript/vocabulary.d.mts. The table is itself written from the headers (make gen), so the client types
# no verb, argument or code of its own. The two limits it reads from where they are declared: string_max in
# protocol/plugin-hostd.json and SOCKET_MSG_MAX_SIZE in include/socket.h.
#
#   tools/ts-client-gen.py                   writes clients/typescript/vocabulary.mjs and vocabulary.d.mts
#   tools/ts-client-gen.py --check           exits 1 when either is not what it writes
#   --table FILE                             another table than protocol/plugin-hostd-protocol.json
#   --out DIR                                another directory than clients/typescript
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = ("vocabulary.mjs", "vocabulary.d.mts")
BANNER = "// GENERATED by tools/ts-client-gen.py from protocol/plugin-hostd-protocol.json: make gen writes it, make check-generated holds it\n"


def fail(msg):
    sys.exit(f"ts-client-gen: {msg}")


# the argument types core.abnf declares by their own rule, which the table's arg_types does not hold: `float`, as the
# grammar spells it (a sign, a decimal or one of nan, inf, infinity in any case)
CORE_TYPES = {
    "float": r"[-+]?(?:[0-9]+(?:\.[0-9]*)?(?:[eE][-+]?[0-9]+)?|\.[0-9]+(?:[eE][-+]?[0-9]+)?|[nN][aA][nN]|[iI][nN][fF](?:[iI][nN][iI][tT][yY])?)",
}
LITERAL = re.compile(r"[a-z0-9-]+(\|[a-z0-9-]+)*")


def js(v, ind=0):
    """a JSON value as TypeScript with single quotes"""
    pad = "  " * (ind + 1)
    if isinstance(v, str):
        return "'" + v.replace("\\", "\\\\").replace("'", "\\'") + "'"
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return json.dumps(v)
    if isinstance(v, list):
        if all(not isinstance(x, (list, dict)) for x in v):
            return "[" + ", ".join(js(x) for x in v) + "]"
        return "[\n" + "".join(f"{pad}{js(x, ind + 1)},\n" for x in v) + "  " * ind + "]"
    if not v:
        return "{}"
    return "{\n" + "".join(f"{pad}{js(k)}: {js(x, ind + 1)},\n" for k, x in v.items()) + "  " * ind + "}"


def build(table_path):
    with open(table_path, encoding="utf-8") as f:
        t = json.load(f)
    with open(os.path.join(ROOT, "protocol/plugin-hostd.json"), encoding="utf-8") as f:
        string_max = json.load(f)["string_max"]
    with open(os.path.join(ROOT, "include/socket.h"), encoding="utf-8") as f:
        m = re.search(r"#define SOCKET_MSG_MAX_SIZE\s+\((\d+) \* (\d+) \* (\d+)\)", f.read())
    if not m:
        fail("include/socket.h: no SOCKET_MSG_MAX_SIZE of the form (a * b * c)")
    msg_max = int(m.group(1)) * int(m.group(2)) * int(m.group(3))
    const = {c["name"]: c["value"] for c in t["constants"]}
    verbs = {}
    for c in sorted(t["commands"], key=lambda c: c["verb"]):
        if c["verb"] in verbs:
            fail(f"{c['verb']} is in the table twice")
        verbs[c["verb"]] = {
            "forms": [{"args": f["args"], "names": f.get("names"), "tail": f["tail"]} for f in c["forms"]],
            "codes": c["codes"],
            "reply": c["reply"],
        }
    types = {k: {"pattern": v["pattern"], "rest": v["rest"]} for k, v in t["arg_types"].items()}
    for c in t["commands"]:
        for f in c["forms"]:
            for a in f["args"]:
                if a in types:
                    continue
                if a in CORE_TYPES:
                    types[a] = {"pattern": CORE_TYPES[a], "rest": False}
                elif a in t["words"].values() or ("|" in a and LITERAL.fullmatch(a)):
                    types[a] = {"pattern": a, "rest": False}  # a word the table declares (all), or literal words a|b: one of them
                else:
                    fail(f"{c['verb']}: the form type {a} is declared in no arg_types, no core type and is no literal word")
    codes = {str(r["resp"]): r["code"] for r in t["reply_codes"]}
    errors = [{"word": e["message"], "code": e["code"]} for e in t["protocol_errors"]]
    mjs = BANNER
    mjs += f"export const PROTOCOL_VERSION = {const['protocol_version']};\n"
    mjs += f"export const DEFAULT_COMMAND_PORT = {const['default_command_port']};\n"
    mjs += f"export const STRING_MAX = {string_max};\n"
    mjs += f"export const MESSAGE_MAX = {msg_max};\n"
    for name, val in (("ARG_TYPES", types), ("VERBS", verbs), ("REPLY_CODES", codes), ("PROTOCOL_ERRORS", errors)):
        mjs += f"export const {name} = {js(val)};\n"
    dts = BANNER
    dts += "export declare const PROTOCOL_VERSION: number;\nexport declare const DEFAULT_COMMAND_PORT: number;\n"
    dts += "export declare const STRING_MAX: number;\nexport declare const MESSAGE_MAX: number;\n"
    dts += "export type Verb =\n" + "".join(f"  | {js(v)}\n" for v in verbs) + ";\n"
    dts += "export type ArgType =\n" + "".join(f"  | {js(v)}\n" for v in types) + ";\n"
    dts += "export interface ArgTypeDecl { readonly pattern: string; readonly rest: boolean }\n"
    dts += "export interface VerbForm { readonly args: readonly ArgType[]; readonly names: readonly string[] | null; readonly tail: boolean }\n"
    dts += "export interface VerbDecl { readonly forms: readonly VerbForm[]; readonly codes: readonly number[]; readonly reply: string | null }\n"
    dts += "export interface ProtocolErrorDecl { readonly word: string; readonly code: number }\n"
    dts += "export declare const ARG_TYPES: Readonly<Record<ArgType, ArgTypeDecl>>;\n"
    dts += "export declare const VERBS: Readonly<Record<Verb, VerbDecl>>;\n"
    dts += "export declare const REPLY_CODES: Readonly<Record<string, string>>;\n"
    dts += "export declare const PROTOCOL_ERRORS: readonly ProtocolErrorDecl[];\n"
    return {"vocabulary.mjs": mjs, "vocabulary.d.mts": dts}


def main(argv):
    check = "--check" in argv
    table = os.path.join(ROOT, "protocol/plugin-hostd-protocol.json")
    out = os.path.join(ROOT, "clients/typescript")
    rest = [a for a in argv if a != "--check"]
    while rest:
        flag, *rest = rest
        if flag not in ("--table", "--out") or not rest:
            fail(f"unknown argument {flag}")
        val, *rest = rest
        if flag == "--table":
            table = val
        else:
            out = val
    want = build(table)
    bad = False
    for name in FILES:
        path = os.path.join(out, name)
        if check:
            try:
                with open(path, encoding="utf-8") as f:
                    have = f.read()
            except OSError as e:
                fail(f"{path}: {e.strerror}")
            if have != want[name]:
                print(f"ts-client-gen: {path} is not what the generator writes: run make gen", file=sys.stderr)
                bad = True
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(want[name])
    if bad:
        sys.exit(1)
    if check:
        print("clients/typescript vocabulary is current")


main(sys.argv[1:])
