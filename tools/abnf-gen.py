# grammar/plugin-hostd-protocol.abnf: the lexical core (grammar/core.abnf, written by hand once) and, after it, the
# rules generated from the verb table (protocol/plugin-hostd-protocol.json): one rule per command, its words typed as
# its format line types them (an alternation where a word has more than one form, told apart by the number of its
# arguments), one per feedback line, one per extension hello grants with hello's reply, the refusals with their error
# words, and one per parse refusal.
# Nothing of a verb is typed here; a verb that moves in the table moves the grammar, and `make check-generated` is red
# until it is written again.
#
#   tools/abnf-gen.py            prints grammar/plugin-hostd-protocol.abnf
#   tools/abnf-gen.py --check    exits 1 when grammar/plugin-hostd-protocol.abnf is not what it prints
import json
import re
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = "grammar/core.abnf"
TABLE = "protocol/plugin-hostd-protocol.json"
OUT = "grammar/plugin-hostd-protocol.abnf"


def fail(msg):
    sys.exit(f"abnf-gen: {msg}")


def read(rel):
    try:
        with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
            return f.read()
    except OSError as e:
        fail(f"{rel}: {e.strerror}")


def rule_name(prefix, word):
    name = prefix + "-" + word.replace("_", "-")
    if not all(c.isalnum() or c == "-" for c in name):
        fail(f'"{word}" makes no ABNF rule name')
    return name


def literal(word):
    if any(c in word for c in '"\x00') or not word.isprintable():
        fail(f'"{word}" cannot be an ABNF string')
    return f'%s"{word}"'


CORE_RULES = set()
CORE_NAMED = set()
ARG_TYPES = {}


def arg_rule(kind):
    """an argument's rule: a rule of core.abnf by that name; a named type of the table's arg_types, one word (its
    pattern, in the table, says which), or core.abnf's rule of its name when it has one (quoted-escaped: a value with
    spaces is not one word); literal words a|b, one of them"""
    if kind in CORE_RULES or (kind in ARG_TYPES and kind in CORE_NAMED):
        return kind
    if kind in ARG_TYPES:
        return "word"
    return "(" + " / ".join(literal(x) for x in kind.split("|")) + ")" if "|" in kind else literal(kind)


def body(word, args, tail):
    rest = bool(args) and ARG_TYPES.get(args[-1], {}).get("rest", False)
    parts = [literal(word)] + [f"SP {arg_rule(a)}" for a in (args[:-1] if rest else args)]
    if tail:
        parts.append("tail")
    return " ".join(parts)


def reply_body(form):
    """a typed reply's rule: resp, 0 or a count, then its arguments"""
    parts = [literal("resp"), "SP", literal("0") if form["resp"] == "0" else "int"]
    args = form["args"]
    rest = bool(args) and ARG_TYPES.get(args[-1], {}).get("rest", False)
    fixed = args[:-1] if (form["repeat"] or rest) else args
    parts += [f"SP {arg_rule(a)}" for a in fixed]
    if rest:
        parts.append("tail")
    elif form["repeat"]:
        parts.append(f"*(SP {arg_rule(args[-1])})")
    return " ".join(parts)


def grammar():
    try:
        table = json.loads(read(TABLE))
    except ValueError as e:
        fail(f"{TABLE}: {e}")
    core = read(CORE)
    # the core rules an argument names: the types of mod-host's own arguments (int, float, word), as the table writes them
    CORE_RULES.update({a for e in table["commands"] for f in e["forms"] if f["origin"] == "mod-host" for a in f["args"]}
                      | {a for e in table["feedback"] if e["origin"] == "mod-host" for a in e["args"]})
    missing = CORE_RULES - set(re.findall(r"^([A-Za-z][A-Za-z0-9-]*)\s*=", core, re.M))
    if missing:
        fail(f"{CORE}: no rule for {', '.join(sorted(missing))}")
    ARG_TYPES.update(table.get("arg_types", {}))
    CORE_NAMED.update(set(re.findall(r"^([A-Za-z][A-Za-z0-9-]*)\s*=", core, re.M)))
    o = [core.rstrip("\n"), ""]
    w = o.append
    w(f"; ---- GENERATED by tools/abnf-gen.py from {TABLE}: do not edit below this line ----")
    w(f"; protocol {table['protocol']}, version {table['version']}, a superset of {table['superset_of']}'s")
    w("")
    commands = table["commands"]
    width = max(len(rule_name("cmd", c["verb"])) for c in commands) + 1
    w("command          = " + "\n                 / ".join(rule_name("cmd", c["verb"]) for c in commands))
    w("")
    for c in commands:
        note = f"; {c['origin']}: {c['declared']}"
        if c["extended_by"]:
            note += f"; extended by {', '.join(c['extended_by'])}"
        if c["sent_by"] == "daemon":
            note += "; sent by the daemon to a worker"
        w(note)
        forms = [body(c["verb"], f["args"], f["tail"]) for f in c["forms"]]
        if len(forms) > 1:
            w("; " + "; ".join(f"form {n + 1}: {f['origin']}" + (f" ({f['declared']})" if f.get("declared") else "")
                               for n, f in enumerate(c["forms"])))
        rhs = forms[0] if len(forms) == 1 else " / ".join(f"({x})" for x in forms)
        w(f"{rule_name('cmd', c['verb']).ljust(width)}= {rhs}")
    w("")
    if table["refused"]:
        w("; words a client of mod-ui may send that no host answers; each is refused and has no rule: "
          + ", ".join(table["refused"]))
        w("")
    feedback = table["feedback"]
    w("feedback         = " + "\n                 / ".join(rule_name("fb", f["line"]) for f in feedback))
    w("")
    width = max(len(rule_name("fb", f["line"])) for f in feedback) + 1
    for f in feedback:
        w(f"; {f['origin']}" + (f": {f['fields']}" if f["fields"] else ""))
        if f["args"] is None:
            w(f"{rule_name('fb', f['line']).ljust(width)}= {literal(f['line'])} tail")
        else:
            forms = [body(f["line"], x["args"], x["tail"]) for x in f.get("forms") or [f]]
            rhs = forms[0] if len(forms) == 1 else " / ".join(f"({x})" for x in forms)
            w(f"{rule_name('fb', f['line']).ljust(width)}= {rhs}")
    w("")
    # the typed replies (#19): a rule per verb with reply_forms, its forms each an alternative; resp 0 or a count, then
    # each argument, a composite one word (its pattern is the table's), the rest type the tail, a repeated last one *(SP)
    typed = [c for c in commands if c.get("reply_forms")]
    if typed:
        w("; the replies the table types, a rule per verb (reply_forms); the reply rule above still takes any resp line")
        w("typed-reply      = " + "\n                 / ".join(rule_name("rp", c["verb"]) for c in typed))
        w("")
        width = max(len(rule_name("rp", c["verb"])) for c in typed) + 1
        for c in typed:
            forms = [reply_body(f) for f in c["reply_forms"]]
            rhs = forms[0] if len(forms) == 1 else " / ".join(f"({x})" for x in forms)
            w(f"{rule_name('rp', c['verb']).ljust(width)}= {rhs}")
        w("")
    w("; the extensions hello grants, and hello's reply: the daemon's version, then each extension it grants, once and in")
    w("; this order")
    exts = table["extensions"]
    if not exts:
        fail(f"{TABLE}: no extension for hello to grant")
    w("extension        = " + " / ".join(rule_name("ext", e["word"]) for e in exts))
    width = max([len(rule_name("ext", e["word"])) + 1 for e in exts] + [len("extension        ")])
    for e in exts:
        w(f"{rule_name('ext', e['word']).ljust(width)}= {literal(e['word'])}")
    w('hello-reply      = %s"resp" SP %s"0" SP int' + "".join(f" [SP {rule_name('ext', e['word'])}]" for e in exts))
    w("")
    w("; a refusal in a session granted errors: its number, then the code the table declares for that number")
    codes = table["reply_codes"]
    if not codes:
        fail(f"{TABLE}: no reply code")
    w("error-reply      = " + "\n                 / ".join(literal(f"resp {c['resp']} {c['code']}") for c in codes))
    w("")
    w("; mod-host's parse refusals, written as their message")
    w("protocol-error   = " + " / ".join(literal(e["message"]) for e in table["protocol_errors"]))
    return "\n".join(o) + "\n"


def main():
    text = grammar()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        try:
            with open(os.path.join(ROOT, OUT), encoding="utf-8") as f:
                have = f.read()
        except OSError:
            have = None
        if have != text:
            sys.exit(f"{OUT} is not what tools/abnf-gen.py writes: run make gen")
        print(f"{OUT} is current")
        return
    if len(sys.argv) > 1:
        fail(f"usage: {sys.argv[0]} [--check]")
    sys.stdout.write(text)


if __name__ == "__main__":
    main()
